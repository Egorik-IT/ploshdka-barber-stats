CREATE TABLE IF NOT EXISTS roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE,
    hierarchy_level integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT NOW()
);
INSERT INTO roles(name,hierarchy_level) VALUES ('developer',100),('manager',80),('admin',50),('employee',10)
ON CONFLICT(name) DO NOTHING;
CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(150) NOT NULL CHECK(username=trim(username) AND username<>''),
    password_hash text NOT NULL,
    display_name varchar(150) NOT NULL CHECK(display_name=trim(display_name) AND display_name<>''),
    role_id integer NOT NULL REFERENCES roles(id),
    is_active boolean NOT NULL DEFAULT true,
    custom_photo_url text,
    yclients_photo_url text,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique ON users(lower(username));
CREATE TABLE IF NOT EXISTS branches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    yclients_company_id bigint UNIQUE,
    is_active boolean NOT NULL DEFAULT true,
    staff_synced_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS user_yclients_links (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    branch_id integer NOT NULL REFERENCES branches(id) ON DELETE CASCADE,
    yclients_staff_id bigint NOT NULL,
    UNIQUE(user_id,branch_id), UNIQUE(branch_id,yclients_staff_id)
);
CREATE TABLE IF NOT EXISTS yclients_staff_cache (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branches(id) ON DELETE CASCADE,
    yclients_staff_id bigint NOT NULL,
    name varchar(255) NOT NULL,
    full_name varchar(255), surname varchar(255), first_name varchar(255), patronymic varchar(255),
    phone varchar(100), email varchar(255), position varchar(255), specialization text, photo_url text,
    yclients_user_id bigint, yclients_employee_id bigint,
    is_active boolean NOT NULL DEFAULT true, is_fired boolean NOT NULL DEFAULT false, is_deleted boolean NOT NULL DEFAULT false,
    dismissal_date date, dismissal_reason text, synced_at timestamptz NOT NULL DEFAULT NOW(),
    UNIQUE(branch_id,yclients_staff_id)
);
CREATE TABLE IF NOT EXISTS user_sessions (
    sid varchar PRIMARY KEY, sess json NOT NULL, expire timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS user_sessions_expire_idx ON user_sessions(expire);
